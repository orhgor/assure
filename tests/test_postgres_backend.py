"""The PostgreSQL backend (db/pg_compat) and the connection discipline built on it.

Replaces the SQLite-era suites (pool release, engine rebind, connection
leakage, raw-file logger tests) with the same guarantees stated for the only
database the app now has: every borrowed connection goes back, a failed
statement neither poisons the connection nor blocks the next writer, the
audit trail counts what it drops, and the SQL the repositories were written
in runs unchanged.
"""

from __future__ import annotations

import sqlite3
import threading
from pathlib import Path

import pytest

from prompt_matrix.db import pg_compat


def _bind(monkeypatch, tmp_path: Path, name: str = "history.sqlite") -> None:
    """Point the process at a fresh per-test schema (derived from DATABASE_PATH)."""
    monkeypatch.setenv("DATABASE_PATH", str(tmp_path / name))
    import prompt_matrix.history as history_mod

    history_mod.DB_PATH = history_mod._resolve_db_path()


