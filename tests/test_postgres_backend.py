def test_placeholders_and_percent_escaping():
    t = pg_compat.translate("SELECT x FROM t WHERE a LIKE '%foo%' AND b = ? AND c = 'it''s'", True)
    assert t.sql == "SELECT x FROM t WHERE a LIKE '%%foo%%' AND b = %s AND c = 'it''s'"
    # Without parameters psycopg does no %-formatting, so nothing is escaped.
    assert pg_compat.translate("SELECT 1 WHERE a LIKE '%x%'", False).sql == "SELECT 1 WHERE a LIKE '%x%'"


def test_ddl_types_are_rewritten_by_position_not_keyword():
    ddl = """CREATE TABLE IF NOT EXISTS t (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        timestamp DATETIME DEFAULT CURRENT_TIMESTAMP,
        score REAL,
        UNIQUE (id, timestamp)
    )"""
    out = pg_compat.translate(ddl, False).sql
    assert "id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in out
    assert "timestamp TIMESTAMP(0) DEFAULT CURRENT_TIMESTAMP" in out  # column keeps its name
    assert "score DOUBLE PRECISION" in out
    assert "UNIQUE (id, timestamp)" in out


def test_insert_or_ignore_and_pragma_and_sqlite_master():
    assert pg_compat.translate("INSERT OR IGNORE INTO t (a) VALUES (?)", True).sql.endswith(
        "ON CONFLICT DO NOTHING"
    )
    assert "information_schema.columns" in pg_compat.translate("PRAGMA table_info(t)", False).sql
    assert pg_compat.translate("PRAGMA journal_mode=WAL;", False).sql == "SELECT 1 WHERE FALSE"
    assert "information_schema.tables" in pg_compat.translate(
        "SELECT name FROM sqlite_master WHERE type='table'", False
    ).sql


def test_schema_is_derived_per_database_path(monkeypatch):
    monkeypatch.delenv("ASSURE_PG_SCHEMA", raising=False)
    monkeypatch.setenv("ASSURE_PG_SCHEMA_FROM_DB_PATH", "1")
    a = pg_compat.current_schema("/tmp/a/history.sqlite")
    b = pg_compat.current_schema("/tmp/b/history.sqlite")
    assert a != b and a.startswith("db_") and b.startswith("db_")
    monkeypatch.setenv("ASSURE_PG_SCHEMA", "public")
    assert pg_compat.current_schema("/tmp/a/history.sqlite") == "public"


