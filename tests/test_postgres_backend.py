def test_migrations_create_the_full_schema(tmp_path, monkeypatch):
    _bind(monkeypatch, tmp_path)
    from prompt_matrix.db.connection import _SCHEMA_VERSION, init_db
    from prompt_matrix.history import db_scope

    init_db()
    with db_scope() as db:
        version = db.execute("SELECT MAX(version) AS v FROM schema_migrations").fetchone()
        assert int(version["v"]) == _SCHEMA_VERSION
        tables = {r[0] for r in db.execute("SELECT name FROM sqlite_master WHERE type='table'")}
        assert {"projects", "jdf_revisions", "substrate_vault", "audit_log", "pipeline_cache"} <= tables
        cols = {r[1] for r in db.execute("PRAGMA table_info(substrate_vault)")}
        assert {"parser_name", "ocr_confidence", "omp_artifact_id"} <= cols


def test_timestamps_render_like_sqlite_and_lastrowid_works(tmp_path, monkeypatch):
    _bind(monkeypatch, tmp_path)
    from prompt_matrix.db.connection import init_db
    from prompt_matrix.history import db_scope

    init_db()
    with db_scope() as db:
        db.execute("INSERT INTO projects (id, title) VALUES (?, ?)", ("p1", "T"))
        row = db.execute("SELECT created_at FROM projects WHERE id = ?", ("p1",)).fetchone()
        assert len(row[0]) == 19 and row[0][10] == " "  # YYYY-MM-DD HH:MM:SS
        cur = db.execute(
            "INSERT INTO system_metrics (cpu_percent, memory_used_mb, memory_total_mb, "
            "swap_used_mb, disk_used_percent, disk_free_gb) VALUES (?,?,?,?,?,?)",
            (1, 2, 3, 4, 5, 6),
        )
        assert cur.lastrowid == 1 and cur.rowcount == 1
        db.commit()


def test_a_failed_statement_leaves_the_connection_usable(tmp_path, monkeypatch):
    """SQLite semantics kept: catch the IntegrityError, keep working on the same handle."""
    _bind(monkeypatch, tmp_path)
    from prompt_matrix.db.connection import init_db
    from prompt_matrix.history import db_scope

    init_db()
    with db_scope() as db:
        db.execute("INSERT INTO projects (id, title) VALUES (?, ?)", ("p1", "T"))
        with pytest.raises(sqlite3.IntegrityError):
            db.execute("INSERT INTO projects (id, title) VALUES (?, ?)", ("p1", "dup"))
        assert db.execute("SELECT COUNT(*) FROM projects").fetchone()[0] == 1
        db.commit()


