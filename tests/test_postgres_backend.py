def test_concurrent_writers_give_every_connection_back(tmp_path, monkeypatch):
    _bind(monkeypatch, tmp_path)
    from prompt_matrix.db.connection import init_db
    from prompt_matrix.db.open_connections import db_open_connection_count
    from prompt_matrix.history import borrowed_connection

    import gc

    init_db()
    # Handles an earlier test never closed are released by the compat
    # connection's finalizer; collect them first so the gauge below measures
    # only this test's own checkouts.
    gc.collect()
    baseline = db_open_connection_count()
    errors: list[str] = []

    def _writer(n: int) -> None:
        try:
            for i in range(5):
                with borrowed_connection() as conn:
                    conn.execute("INSERT INTO projects (id, title) VALUES (?, ?)", (f"p{n}-{i}", "T"))
                    conn.commit()
        except Exception as exc:  # pragma: no cover - reported below
            errors.append(repr(exc))

    threads = [threading.Thread(target=_writer, args=(n,)) for n in range(8)]
    for t in threads:
        t.start()
    for t in threads:
        t.join(timeout=60)
    assert errors == []
    gc.collect()
    # No growth: every writer gave its connection back (a lower reading only
    # means another test's leftover was collected meanwhile).
    assert db_open_connection_count() <= baseline
    with borrowed_connection() as conn:
        assert conn.execute("SELECT COUNT(*) FROM projects").fetchone()[0] == 40


def test_audit_logger_writes_through_the_pool_and_counts_drops(tmp_path, monkeypatch):
    _bind(monkeypatch, tmp_path)
    from prompt_matrix.db.connection import init_db
    from prompt_matrix.db.open_connections import db_open_connection_count
    from prompt_matrix.history import borrowed_connection
    from prompt_matrix.lib.logger import AuditLogger, audit_drop_count

    init_db()
    with borrowed_connection() as conn:
        conn.execute("INSERT INTO projects (id, title) VALUES ('proj-1', 'proj-1')")
        conn.commit()
    baseline_open = db_open_connection_count()
    drops = audit_drop_count()
    audit = AuditLogger(str(tmp_path / "history.sqlite"))
    audit.log_audit("req-1", "proj-1", "INQUIRE_STREAM", success=True, duration_ms=42)
    # An unknown project is refused by the FK: counted, never raised.
    audit.log_audit("req-2", "no-such-project", "INQUIRE_STREAM", success=True)
    assert audit_drop_count() == drops + 1
    assert db_open_connection_count() == baseline_open
    with borrowed_connection() as conn:
        rows = conn.execute("SELECT request_id, success, duration_ms FROM audit_log").fetchall()
    assert [tuple(r) for r in rows] == [("req-1", 1, 42)]


def test_run_with_db_retry_retries_locked_errors():
    from prompt_matrix.db.connection import run_with_db_retry

    calls = {"n": 0}

    def flaky():
        calls["n"] += 1
        if calls["n"] < 3:
            raise sqlite3.OperationalError("database is locked")
        return "ok"

    assert run_with_db_retry(flaky, backoff_s=0.0) == "ok"
    assert calls["n"] == 3


def test_get_engine_rebinds_when_database_url_changes(monkeypatch):
    from prompt_matrix.db import pool

    pool.dispose_engine()
    url = pg_compat.database_url()
    assert url
    eng1 = pool.get_engine()
    monkeypatch.setenv("DATABASE_URL", url + ("&" if "?" in url else "?") + "application_name=rebind")
    eng2 = pool.get_engine()
    assert eng2 is not eng1
    pool.dispose_engine()
