CATALOGS = {"en": EN, "es": ES, "zh": ZH, "fr": FR, "de": DE, "ja": JA, "tr": TR}

def normalize_locale(value: str | None) -> str:
    raw = (value or "en").strip().lower().replace("_", "-")
    if raw.startswith("zh"):
        return "zh"
    if raw.startswith("es"):
        return "es"
    if raw.startswith("fr"):
        return "fr"
    if raw.startswith("de"):
        return "de"
    if raw.startswith("ja"):
        return "ja"
    if raw.startswith("tr"):
        return "tr"
    if raw.startswith("en"):
        return "en"
    return "en" if raw not in CATALOGS else raw


def catalog(lang: str | None = None) -> dict[str, str]:
    locale = normalize_locale(lang)
    base = dict(EN)
    base.update(CATALOGS.get(locale) or {})
    return base


def t(key: str, lang: str | None = None, **fmt) -> str:
    text = catalog(lang).get(key) or EN.get(key) or key
    if fmt:
        try:
            return text.format(**fmt)
        except (KeyError, IndexError, ValueError):
            return text
    return text


def intent_plain(lang: str | None = None) -> dict[str, str]:
    return {
        "research": t("intent.research", lang),
        "design": t("intent.design", lang),
        "comparison": t("intent.comparison", lang),
        "debug": t("intent.debug", lang),
        "analysis": t("intent.analysis", lang),
    }


def friendly_error(raw: str, lang: str | None = None) -> str:
    text = (raw or "").strip()
    lower = text.lower()
    if "sends per day" in lower or "today's limit" in lower:
        if "10" in text:
            return t("error.quota", lang)
        if "100" in text:
            return t("error.quota.pro", lang)
        return t("error.quota", lang)
    if "workflow timeout" in lower or "full workflow timeout" in lower:
        return t("error.workflow_timeout", lang)
    if "run aborted due to timeout" in lower or ("timeout" in lower and "60" in text):
        return t("error.timeout", lang)
    if "context window" in lower or "too long" in lower:
        return t("error.overflow", lang)
    if "lint" in lower:
        return t("error.lint", lang)
    if "please connect" in lower or ("api key" in lower and "connect" in lower):
        return t("error.connect", lang)
    if "ollama is not installed" in lower:
        return t("error.ollama", lang)
    if "file paths" in lower or "extra context" in lower:
        return t("error.glob", lang)
    if "something went wrong" in lower or "request failed" in lower:
        return t("error.request", lang)
    if "upgrade to pro" in lower:
        return t("upgrade", lang)
    return text
